public class DataType{
	public static void main(String[] args){
		byte myAge = 25;
		short quantity = 25000;
		int nigeriaPopulation = 20000000;
		long worldsPopulation = 67400000000000L;
		
		System.out.printf("I am %d years old%n" ,myAge);
		System.out.printf("I ordered %d quantity of phones %n" ,quantity);
		System.out.printf("Nigeria's population is %d%n" ,nigeriaPopulation);
		System.out.printf("World population is %d" ,worldsPopulation);
		
	}
}